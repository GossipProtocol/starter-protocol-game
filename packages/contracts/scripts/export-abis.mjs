// Exports the ABIs of the beeef contracts (and the Doppler contracts the apps call) from forge's out/ into
// packages/sdk/src/abis/*.ts as `as const` arrays, so viem and Ponder get full type inference.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "out");
const dest = join(here, "..", "..", "sdk", "src", "abis");
mkdirSync(dest, { recursive: true });

const contracts = [
  ["BeeefRoundFactory.sol", "BeeefRoundFactory"],
  ["BeeefOracle.sol", "BeeefOracle"],
  ["BeeefClockHook.sol", "BeeefClockHook"],
  ["BeeefFeeSplitter.sol", "BeeefFeeSplitter"],
  ["BeeefRegistry.sol", "BeeefRegistry"],
  ["IDoppler.sol", "IAirlock"],
  ["IDoppler.sol", "IPredictionMigrator"],
  ["IAggregatorV3.sol", "IAggregatorV3"],
  ["IRobinhoodStockToken.sol", "IRobinhoodStockToken"],
  // PredictionMigrator events (EntryMigrated, Claimed) come from the Doppler artifact.
  ["PredictionMigrator.sol", "PredictionMigrator"],
];

const index = [];
for (const [file, name] of contracts) {
  const { abi } = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  const id = name.charAt(0).toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by packages/contracts/scripts/export-abis.mjs. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${id} } from "./${name}.js";`);
}
writeFileSync(join(dest, "index.ts"), `// Generated. Do not edit.\n${index.join("\n")}\n`);
console.log(`exported ${contracts.length} ABIs to ${dest}`);
